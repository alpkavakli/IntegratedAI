// @ts-check
/**
 * Copy pdf.js (Mozilla's PDF reader) into the extension, for reading the text of an uploaded CV:
 *   extension/vendor/pdf.mjs, extension/vendor/pdf.worker.mjs
 *
 *   npm run vendor:pdf
 *
 * The "legacy" build is used: it also runs on the oldest Chrome the extension supports. Only whitespace and
 * syntax are minified (names stay readable, for Chrome Web Store review), as for the Anthropic SDK. Run it again
 * after upgrading pdfjs-dist. Only text is read from PDFs, so pdf.js's fonts, character maps, image decoders and
 * viewer are not copied.
 */

import { build } from 'esbuild';
import { copyFileSync, readFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkg = JSON.parse(readFileSync(`${root}/node_modules/pdfjs-dist/package.json`, 'utf8'));

for (const name of ['pdf', 'pdf.worker']) {
  await build({
    entryPoints: [`${root}/node_modules/pdfjs-dist/legacy/build/${name}.mjs`],
    outfile: `${root}/extension/vendor/${name}.mjs`,
    bundle: false,
    format: 'esm',
    platform: 'browser',
    minifyWhitespace: true,
    minifySyntax: true,
    legalComments: 'eof',
    banner: {
      js: `// Vendored pdfjs-dist ${pkg.version} (${pkg.license}), legacy build, for reading the text of an uploaded PDF.\n// Generated by scripts/vendor-pdf.js; do not edit. Source: https://github.com/mozilla/pdf.js`,
    },
    logLevel: 'warning',
  });
  console.log(`extension/vendor/${name}.mjs  ${(statSync(`${root}/extension/vendor/${name}.mjs`).size / 1024).toFixed(0)} KB`);
}

// Apache-2.0 asks for the license to ship with every copy: next to the files.
copyFileSync(`${root}/node_modules/pdfjs-dist/LICENSE`, `${root}/extension/vendor/pdfjs-LICENSE.txt`);
